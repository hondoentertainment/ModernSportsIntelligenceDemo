#!/usr/bin/env node
/**
 * Bootstrap launch-ops test users on the linked Supabase project:
 *   1) ops admin (promoted to profiles.role = admin)
 *   2) GDPR throwaway (for authenticated export / delete)
 *
 * Writes credentials to gitignored `.env.launch-ops.local`.
 *
 * Usage: node scripts/bootstrap-launch-ops.mjs
 */
import { createClient } from '@supabase/supabase-js';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, '.env.launch-ops.local');

function loadEnvFile(rel) {
  const path = resolve(ROOT, rel);
  if (!existsSync(path)) return;
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const eq = t.indexOf('=');
    if (eq <= 0) continue;
    const key = t.slice(0, eq).trim();
    let value = t.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = value;
  }
}

loadEnvFile('.env.supabase.local');

const url = (process.env.SUPABASE_URL || '').trim();
const serviceKey = (process.env.SUPABASE_SERVICE_ROLE_KEY || '').trim();
const anonKey = (process.env.SUPABASE_ANON_KEY || process.env.VITE_SUPABASE_ANON_KEY || '').trim();
if (!url || !serviceKey || !anonKey) {
  console.error('Need SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY, SUPABASE_ANON_KEY in .env.supabase.local');
  process.exit(1);
}

const admin = createClient(url, serviceKey, {
  auth: { persistSession: false, autoRefreshToken: false },
});

function password() {
  return `Msi!${randomBytes(18).toString('base64url')}`;
}

async function ensureUser(email, pwd) {
  const { data: listed, error: listErr } = await admin.auth.admin.listUsers({ page: 1, perPage: 200 });
  if (listErr) throw listErr;
  const existing = (listed?.users ?? []).find((u) => (u.email || '').toLowerCase() === email.toLowerCase());
  if (existing) {
    const { error } = await admin.auth.admin.updateUserById(existing.id, {
      password: pwd,
      email_confirm: true,
    });
    if (error) throw error;
    return existing.id;
  }
  const { data, error } = await admin.auth.admin.createUser({
    email,
    password: pwd,
    email_confirm: true,
  });
  if (error) throw error;
  return data.user.id;
}

async function setRole(userId, role) {
  const { error } = await admin.from('profiles').update({ role }).eq('id', userId);
  if (error) throw error;
}

const adminEmail = 'msi-launch-admin@example.com';
const gdprEmail = 'msi-launch-gdpr@example.com';
const adminPwd = password();
const gdprPwd = password();

const adminId = await ensureUser(adminEmail, adminPwd);
await setRole(adminId, 'admin');
const gdprId = await ensureUser(gdprEmail, gdprPwd);

const lines = [
  '# Generated by scripts/bootstrap-launch-ops.mjs — do not commit',
  `SUPABASE_URL=${url}`,
  `VITE_SUPABASE_URL=${url}`,
  `SUPABASE_ANON_KEY=${anonKey}`,
  `VITE_SUPABASE_ANON_KEY=${anonKey}`,
  `PLAYWRIGHT_SUPABASE_URL=${url}`,
  `PLAYWRIGHT_SUPABASE_ANON_KEY=${anonKey}`,
  `PLAYWRIGHT_REAL_AUTH=1`,
  `PLAYWRIGHT_TEST_EMAIL=${gdprEmail}`,
  `PLAYWRIGHT_TEST_PASSWORD=${gdprPwd}`,
  `MSI_LAUNCH_ADMIN_EMAIL=${adminEmail}`,
  `MSI_LAUNCH_ADMIN_PASSWORD=${adminPwd}`,
  `MSI_LAUNCH_ADMIN_ID=${adminId}`,
  `MSI_LAUNCH_GDPR_EMAIL=${gdprEmail}`,
  `MSI_LAUNCH_GDPR_PASSWORD=${gdprPwd}`,
  `MSI_LAUNCH_GDPR_ID=${gdprId}`,
  '',
];

writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`Wrote ${OUT}`);
console.log(`Admin: ${adminEmail} (role=admin, id=${adminId})`);
console.log(`GDPR throwaway: ${gdprEmail} (id=${gdprId})`);
process.exit(0);
